# 🎬 Function to fetch poster + ratings + extra metadata
@st.cache_data(show_spinner=False)
def get_movie_data(title):
    url = f"http://www.omdbapi.com/?t={title}&apikey={OMDB_API_KEY}"
    response = requests.get(url).json()

    poster_url = response.get("Poster")
    imdb_rating = response.get("imdbRating", "N/A")
    rt_rating = "N/A"
    for r in response.get("Ratings", []):
        if r["Source"] == "Rotten Tomatoes":
            rt_rating = r["Value"]

    plot = response.get("Plt", "N/A")
    director = response.get("Director", "N/A")
    runtime = response.get("Runtime", "N/A")

    # ✅ Only return values here
    return poster_url, imdb_rating, rt_rating, plot, director, runtime

# 🔍 Function to fetch live suggestions from OMDb
@st.cache_data(show_spinner=False)
def get_movie_suggestions(query):
    url = f"http://www.omdbapi.com/?s={query}&apikey={OMDB_API_KEY}"
    response = requests.get(url).json()
    if response.get("Search"):
        return [movie["Title"] for movie in response["Search"]]
    return []



