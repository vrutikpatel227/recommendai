from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

def get_favorites_recommendations(favorites, movies_df):
    if not favorites:
        return pd.DataFrame()  # no favorites yet

    # Convert genres text into numeric vectors
    tfidf = TfidfVectorizer(stop_words="english")
    tfidf_matrix = tfidf.fit_transform(movies_df["genres"].fillna(""))

    # Compute cosine similarity between all movies
    similarities = cosine_similarity(tfidf_matrix, tfidf_matrix)

    # Map titles to indices
    indices = pd.Series(movies_df.index, index=movies_df["title"]).drop_duplicates()

    # Get indices of favorite movies
    fav_indices = [indices[fav] for fav in favorites if fav in indices]

    if not fav_indices:
        return pd.DataFrame()  # no valid favorites found

    # Average similarity scores across favorites
    avg_sim = similarities[fav_indices].mean(axis=0)

    # Sort by similarity
    similar_indices = avg_sim.argsort()[::-1]

    # Exclude already saved favorites
    recommended = movies_df.iloc[similar_indices]
    recommended = recommended[~recommended["title"].isin(favorites)]

    return recommended.head(6)


# 📄 Function to generate PDF
def generate_pdf(similar_movies, collab_titles, hybrid_titles):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(200, 10, txt="RecommendAI - Movie Recommendations", ln=True, align="C")
    pdf.ln(10)

    def draw_table(title, dataframe, columns):
        pdf.set_font("Arial", 'B', 14)
        pdf.cell(200, 10, txt=title, ln=True)
        pdf.set_font("Arial", 'B', 12)
        pdf.set_fill_color(230, 230, 230)
        col_widths = [90, 90]
        for col in columns:
            pdf.cell(col_widths[columns.index(col)], 8, col.capitalize(), border=1, fill=True)
        pdf.ln(8)
        pdf.set_font("Arial", '', 11)
        for _, row in dataframe.iterrows():
            pdf.cell(col_widths[0], 8, str(row[columns[0]])[:45], border=1)
            pdf.cell(col_widths[1], 8, str(row[columns[1]])[:45], border=1)
            pdf.ln(8)
        pdf.ln(5)

    draw_table("Content-Based Recommendations", similar_movies[["title", "genres"]], ["title", "genres"])
    collab_titles = collab_titles.assign(genres="N/A")
    draw_table("Collaborative Recommendations", collab_titles[["title", "genres"]], ["title", "genres"])
    hybrid_titles = hybrid_titles.assign(genres="N/A")
    draw_table("Hybrid Recommendations", hybrid_titles[["title", "genres"]], ["title", "genres"])

    pdf.set_y(-15)
    pdf.set_font("Arial", 'I', 10)
    pdf.cell(0, 10, f"Generated by RecommendAI - Page {pdf.page_no()}", 0, 0, 'C')

    pdf_bytes = pdf.output(dest="S").encode("latin-1") if isinstance(pdf.output(dest="S"), str) else bytes(pdf.output(dest="S"))
    return pdf_bytes

# 🔄 Real Recommendation Engine (cosine similarity on genres)
def recommend(movie_title, df, top_n=5):
    tfidf = TfidfVectorizer(stop_words="english")
    tfidf_matrix = tfidf.fit_transform(df["genres"].fillna(""))

    cosine_sim = cosine_similarity(tfidf_matrix, tfidf_matrix)
    indices = pd.Series(df.index, index=df["title"]).drop_duplicates()
    idx = indices[movie_title]

    sim_scores = list(enumerate(cosine_sim[idx]))
    sim_scores = sorted(sim_scores, key=lambda x: x[1], reverse=True)
    sim_scores = sim_scores[1:top_n+1]

    movie_indices = [i[0] for i in sim_scores]
    return df["title"].iloc[movie_indices].tolist()

